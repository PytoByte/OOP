package ru.nsu.vmarkidonov;

/**
 * Перечисление кодов команд и статусов сетевого протокола взаимодействия сервера и воркера.
 */
public enum Protocol {

    /**
     * Запрос текущего состояния вычислительного узла (пинг).
     */
    STATUS,

    /**
     * Подтверждение активности и готовности воркера к работе.
     */
    OK,

    /**
     * Передача пакета чисел от сервера к воркеру для выполнения вычислений.
     */
    TASK,

    /**
     * Подтверждение успешного приема вычислительной задачи воркером.
     */
    ACCEPT,

    /**
     * Отправка финального результата обработки блока данных на сервер.
     */
    RESULT,

    /**
     * Сигнал принудительной отмены текущей выполняемой задачи.
     */
    STOP;

    /**
     * Возвращает элемент протокола по его порядковому номеру.
     *
     * @param ordinal порядковый номер команды или статуса
     * @return соответствующий элемент перечисления
     * @throws IllegalArgumentException если переданный код выходит за границы допустимых значений
     */
    public static Protocol fromOrdinal(int ordinal) {
        if (ordinal < 0 || ordinal >= values().length) {
            throw new IllegalArgumentException("Неизвестный код протокола: " + ordinal);
        }
        return values()[ordinal];
    }
}