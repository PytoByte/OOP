package game.model;

/**
 * Перечисление возможных направлений движения игровых объектов.
 * Используется змейкой для определения вектора перемещения в сетке координат.
 */
public enum Direction {
    /** Движение вверх (уменьшение координаты Y). */
    UP,
    /** Движение вниз (увеличение координаты Y). */
    DOWN,
    /** Движение влево (уменьшение координаты X). */
    LEFT,
    /** Движение вправо (увеличение координаты X). */
    RIGHT
}