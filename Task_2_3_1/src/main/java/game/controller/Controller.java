package game.controller;

import javafx.scene.Scene;

/**
 * Базовый интерфейс для всех игровых контроллеров.
 * Определяет жизненный цикл компонента управления, включая инициализацию,
 * обновление состояния и обработку событий пользовательского интерфейса.
 */
public interface Controller {
    /**
     * Возвращает объект модели, которым управляет данный контроллер.
     *
     * @return объект данных (например, {@link Snake} или {@link Food}).
     */
    Object getModel();

    /**
     * Настраивает обработку событий (ввод с клавиатуры, мыши) для текущей сцены.
     * По умолчанию метод пуст.
     *
     * @param scene объект {@link Scene} JavaFX, к которому привязываются слушатели.
     */
    default void setupEvents(Scene scene) {
    }

    /**
     * Вызывается на каждом "тике" игрового таймера для обновления логики объекта.
     * По умолчанию метод пуст.
     */
    default void update() {
    }

    /**
     * Сбрасывает состояние контроллера и управляемой им модели к начальным значениям.
     * Используется при старте новой игры или после поражения.
     */
    void restart();
}
