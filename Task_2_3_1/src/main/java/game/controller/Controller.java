package game.controller;

import javafx.scene.Scene;

/**
 * Базовый интерфейс для вспомогательных игровых контроллеров.
 * Позволяет главному контроллеру управлять вводом и жизненным циклом компонентов.
 */
public interface Controller {
    /**
     * Настраивает обработку событий (ввод с клавиатуры, мыши) для текущей сцены.
     * По умолчанию метод пуст.
     *
     * @param scene объект Scene из JavaFX.
     */
    default void setupEvents(Scene scene) {}

    /**
     * Вызывается на каждом "тике" игрового таймера для обновления
     * состояния самого контроллера (например, применение буфера направления).
     * По умолчанию метод пуст.
     */
    default void update() {}

    /**
     * Сбрасывает состояние контроллера к начальным значениям.
     */
    void restart();
}