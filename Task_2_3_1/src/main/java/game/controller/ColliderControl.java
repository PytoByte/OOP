package game.controller;

import game.model.Collider;
import game.model.Point;

/**
 * Интерфейс для контроллеров, поддерживающих логику обработки столкновений.
 * Определяет поведение объекта в момент физического контакта с другой сущностью.
 */
public interface ColliderControl {
    /**
     * Вызывается при обнаружении столкновения текущего объекта с другим коллайдером.
     *
     * @param model объект-коллайдер, с которым произошло взаимодействие.
     * @param p точка на игровом поле, в которой зафиксировано касание.
     */
    void collide(Collider model, Point p);
}
